const fs=require('node:fs');
const assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const app=fs.readFileSync('app.js','utf8');
const sw=fs.readFileSync('sw.js','utf8');
const css=fs.readFileSync('styles.css','utf8');
const version=html.match(/app\.js\?v=(\d+)/)?.[1];
assert.ok(version,'App version missing');
assert.ok(html.includes('styles.css?v='+version),'CSS and JS version mismatch');
assert.ok(sw.includes('cx-tv-v'+version),'Service worker cache version mismatch');
assert.ok(sw.includes('app.js?v='+version),'Service worker app asset mismatch');
assert.ok(sw.includes('styles.css?v='+version),'Service worker CSS asset mismatch');
assert.ok(app.includes('function refreshHomeToday()'),'Home refresh helper missing');
assert.ok(app.includes('renderFavoriteHome();refreshHomeToday();'),'Home not refreshed after sports feed');
assert.ok(app.includes('sliderLocalDate(e)===dateKey(0)'),'Home local day filtering missing');
assert.ok(app.includes('scheduleWithDeadline(mlbGames([0])'),'MLB home feed timeout missing');
assert.ok(css.includes('.home-today-grid'),'Home layout CSS missing');
assert.ok(!app.includes('window.confirm('),'Native confirmation dialog regression');
assert.ok(app.includes('async function fetchSportsDbDays(offsets)'),'Bounded SportsDB worker missing');
assert.ok(app.includes('Math.min(4,queue.length)'),'SportsDB concurrency cap missing');
assert.ok(app.includes('SportsDB HTTP '),'SportsDB HTTP error detection missing');
assert.ok(app.includes('dateEvent:g.startTimeUTC?new Intl.DateTimeFormat("en-CA",{timeZone:"America/Santo_Domingo"})'),'NHL Dominican local date normalization missing');
assert.ok(app.includes('finally(()=>clearTimeout(timeoutId))'),'Feed timeout cleanup missing');
assert.ok(app.includes('serviceWorker.register("./sw.js?v='+version+'",{updateViaCache:"none"})'),'Service worker registration version mismatch');
assert.ok(sw.includes('await cache.addAll(CORE)'),'Offline shell install must be atomic');
assert.ok(sw.includes('if(!insideScope(url))return'),'Service worker scope guard missing');
assert.ok(sw.includes('if(!isAppAsset(url))return'),'Dynamic request caching regression');
assert.ok(sw.includes('const INDEX=new URL("./index.html",SCOPE).href'),'Offline navigation fallback missing');
assert.ok(app.includes('if(error)throw error;'),'Profile query errors must fail closed');
assert.ok(app.includes('if(!p||p.status!=="active")'),'Inactive or missing profiles must be denied');
assert.ok(app.includes('currentUser=null;currentProfile=null;'),'Session state must reset before verification');
assert.ok(app.includes('if(!currentUser||currentProfile?.role!=="admin")return dashboard();'),'Admin UI guard missing');
console.log('Static checks passed for version '+version);
