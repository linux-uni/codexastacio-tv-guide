const fs=require('node:fs');
const assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const app=fs.readFileSync('app.js','utf8');
const sw=fs.readFileSync('sw.js','utf8');
const css=fs.readFileSync('styles.css','utf8');
const version=html.match(/app\.js\?v=(\d+)/)?.[1];
assert.ok(version,'App version missing');
assert.ok(html.includes('styles.css?v='+version),'CSS and JS version mismatch');
assert.ok(sw.includes('cx-tv-v'+version),'Service worker cache version mismatch');
assert.ok(sw.includes('app.js?v='+version),'Service worker app asset mismatch');
assert.ok(sw.includes('styles.css?v='+version),'Service worker CSS asset mismatch');
assert.ok(app.includes('function refreshHomeToday()'),'Home refresh helper missing');
assert.ok(app.includes('renderFavoriteHome();refreshHomeToday();'),'Home not refreshed after sports feed');
assert.ok(app.includes('sliderLocalDate(e)===dateKey(0)'),'Home local day filtering missing');
assert.ok(app.includes('scheduleWithDeadline(mlbGames([0])'),'MLB home feed timeout missing');
assert.ok(css.includes('.home-today-grid'),'Home layout CSS missing');
assert.ok(!app.includes('window.confirm('),'Native confirmation dialog regression');
console.log('Static checks passed for version '+version);
